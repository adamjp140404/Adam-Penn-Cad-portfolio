# Same processing as Data_Extraction.py
pflanz_dict = {}
for name, file_id in zip(["0.5", "1", "2"], ["5", "1", "2"]):
    entire_curve = np.empty((0, 2))
    for j in (1, 2):
        data_array = np.array(RAW[(file_id, j)], dtype=float)
        if j > 1:  # Curve II: rescale x and pin the end point at (1000, 1)
            data_array[:, 0] *= 100
            data_array = np.vstack([data_array, [1000, 1]])
        entire_curve = np.vstack([entire_curve, data_array])
    pflanz_dict[name] = PchipInterpolator(
        np.log10(entire_curve[:, 0]), np.log10(entire_curve[:, 1])
    )

with open(PICKLE_PATH, "wb") as f:
    pickle.dump({"MIT_coeffs": mit_coeffs, "Pflanz_functions": pflanz_dict}, f)

